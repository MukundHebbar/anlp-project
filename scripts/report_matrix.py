#!/usr/bin/env python3
"""Transfer-matrix report: every checkpoint on every task, with paired differences against the untrained student.

    python3 scripts/report_matrix.py                    # Jev judge + strict gates (judged-scores.jev.jsonl)
    python3 scripts/report_matrix.py --judge deepseek   # the earlier DeepSeek scores (judged-scores.jsonl)

Each checkpoint's test evaluation lives in artifacts/baselines/final-v3/test/matrix-<key>/ (scores.jsonl
from the deterministic scorers, judged-scores.jsonl from scripts/judge_baseline.py). Intervals are 95%
bootstrap intervals over questions (2,000 resamples); differences are paired on the same questions.
"""

import json
import random
import statistics as st
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
TEST = REPO / "artifacts" / "baselines" / "final-v3" / "test"
OUT = REPO / "artifacts" / "transfer-matrix"
JUDGE = "deepseek" if "--judge" in sys.argv and sys.argv[sys.argv.index("--judge") + 1] == "deepseek" else "jev"
JUDGED = "judged-scores.jsonl" if JUDGE == "deepseek" else "judged-scores.jev.jsonl"

# Row order: the untrained student, then each training arm. Missing checkpoints are skipped.
ROWS = [("base", "Untrained student")]
for task, name in (("solve", "SOLVE"), ("judge", "JUDGE"), ("reconstruct", "RECONSTRUCT")):
    ROWS.append((f"sft-{task}", f"{name} SFT warm-up only"))
    for step in (52, 104, 156):
        ROWS.append((f"opd-{task}-s{step}", f"{name} SFT → OPD, step {step}"))


def load(key: str, name: str) -> dict:
    p = TEST / f"matrix-{key}" / name
    return {x["uid"]: x for x in map(json.loads, p.open())} if p.exists() else {}


def per_question(det: dict, jud: dict) -> dict[str, dict[str, float]]:
    """uid -> value for each metric. RECONSTRUCT: unusable answers score 0; unresolved judgments are left out."""
    m = {k: {} for k in ("solve_acc", "judge_verdict", "judge_step", "judge_score", "recon_score", "recon_same")}
    for u, s in det.items():
        if s["task"] == "solve":
            m["solve_acc"][u] = float(s["answer_status"] == "correct")
        elif s["task"] == "judge":
            j = jud.get(u)
            if JUDGE == "jev":  # strict: a hedged or contradictory answer is wrong
                if j is None:
                    continue
                m["judge_verdict"][u] = float(j["verdict_correct_strict"])
                if s["label"] == "incorrect":
                    m["judge_step"][u] = float(j["step_correct_strict"])
            else:
                m["judge_verdict"][u] = float(s["verdict_correct"])
                if s["label"] == "incorrect":
                    m["judge_step"][u] = float(s["step_correct"])
            if j and j.get("score_100") is not None:
                m["judge_score"][u] = j["score_100"]
        else:
            j = jud.get(u)
            if not s["parsed"] or (j and j.get("status") == "unusable_response"):
                m["recon_score"][u] = 0.0
                m["recon_same"][u] = 0.0
            elif j and j.get("score_100") is not None:
                m["recon_score"][u] = j["score_100"]
                m["recon_same"][u] = float(j.get("semantic_equivalent") is True)
    return m


def boot(vals: list[float], seed: int = 0):
    if not vals:
        return None
    rng = random.Random(seed)
    means = sorted(st.mean(rng.choices(vals, k=len(vals))) for _ in range(2000))
    return st.mean(vals), means[49], means[1949]


def fmt(ci, pct: bool, sign: bool = False) -> str:
    if ci is None:
        return "—"
    s = 100 if pct else 1
    f = (lambda v: f"{v * s:+.1f}") if sign else (lambda v: f"{v * s:.1f}")
    return f"{f(ci[0])} [{f(ci[1])}, {f(ci[2])}]"


METRICS = [("solve_acc", "SOLVE accuracy (%)", True), ("judge_verdict", "JUDGE verdict accuracy (%)", True),
           ("recon_score", "RECONSTRUCT PC-v4 /100", False)]
SECONDARY = [("judge_step", "JUDGE first wrong step (%)", True), ("judge_score", "JUDGE V/L/E/M /100", False),
             ("recon_same", "RECONSTRUCT same original question (%)", True)]


def main():
    data = {}
    for key, label in ROWS:
        det = load(key, "scores.jsonl")
        if det:
            data[key] = (label, per_question(det, load(key, JUDGED)),
                         bool(load(key, JUDGED)))
    if "base" not in data:
        sys.exit("no base evaluation yet")
    base = data["base"][1]
    lines = ["# Transfer matrix: SOLVE, JUDGE and RECONSTRUCT", "",
             "Generated by `scripts/report_matrix.py`. Student Qwen3.5-2B, teacher Qwen3.8-27B; FINAL-v3 test, "
             "400 questions per task, judge " + ("Jev with strict gates" if JUDGE == "jev" else "DeepSeek V4.1 Flash") + ", protocol v2 (T 1.0, one sample, 32k: answers capped at 16k are continued from "
             "their own tokens to 32k). Values are means with 95% bootstrap intervals over questions; Δ is paired "
             "against the untrained student on the same questions. RECONSTRUCT: unusable answers score 0, "
             "unresolved judgments are excluded.", ""]
    for title, metrics in (("Primary metrics", METRICS), ("Secondary metrics", SECONDARY)):
        lines += [f"## {title}", "", "| Checkpoint | " + " | ".join(n for _, n, _ in metrics) + " |",
                  "|---|" + "---:|" * len(metrics)]
        for key, (label, m, judged) in data.items():
            cells = [fmt(boot(list(m[k].values())), pct) for k, _, pct in metrics]
            lines.append(f"| {label}{'' if judged else ' (not yet judged)'} | " + " | ".join(cells) + " |")
        lines += ["", f"### Δ against the untrained student ({title.lower()})", "",
                  "| Checkpoint | " + " | ".join(n for _, n, _ in metrics) + " |", "|---|" + "---:|" * len(metrics)]
        for key, (label, m, judged) in data.items():
            if key == "base":
                continue
            cells = []
            for k, _, pct in metrics:
                both = sorted(set(m[k]) & set(base[k]))
                cells.append(fmt(boot([m[k][u] - base[k][u] for u in both]), pct, sign=True) + f" (n={len(both)})")
            lines.append(f"| {label} | " + " | ".join(cells) + " |")
        lines.append("")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / ("REPORT.md" if JUDGE == "jev" else "REPORT-deepseek.md")).write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
